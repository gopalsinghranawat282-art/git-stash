SELECT * FROM PRODUCTS;
/* 2. CASE WITH AND  & OR OPERATOR - STOCK STATUS
M WE WILL CLASSIFY PRODUCTS  BASED ON QUANTITY AVAIBLABLE

IN STOCK IF QUANTITY IS 10 OR MORE
LIMITED STOCK IF QUINTITY IS BETWEEN 5 AND 9.
OUT OF STOCK SOON IF QUANTITY IS LESS THEN 5.
*/

	SELECT PRODUCT_NAME,QUANTITY,

	CASE 
	   WHEN QUANTITY >=10 THEN 'INSTOCK'
	   WHEN QUANTITY  BETWEEN 6 AND 9 THEN 'LIMITED STOCK'
	   ELSE 'OUT OF STOCK SOON'
	   END AS STOCKS_STATUS
	   FROM PRODUCTS;

  SELECT PRODUCT_NAME,CATEGORY,

  CASE 
  WHEN CATEGORY LIKE 'ELECTRONICS%' THEN 'ELECTRONIC ITEM'
  WHEN CATEGORY LIKE 'FURNITURE%' THEN 'FURNITURE ITEM'
  ELSE 'ACCESSORY ITEM'
  END AS CATEGORY_STATUS
  FROM PRODUCTS;



